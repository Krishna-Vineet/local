def model(name, file, purpose, fields, *, indexes=None, ttl=None, flags=None):
    return {
        "name": name,
        "file": file,
        "purpose": purpose,
        "fields": fields,      # (field, type, notes)
        "indexes": indexes or [],
        "ttl": ttl,
        "flags": flags or [],
    }


